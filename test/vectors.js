// Cross-implementation test vectors (docs/test-vectors.json).
// The Node implementation is the reference; ios/CameraTriggerKit tests read
// the same file. Regenerate with: node test/vectors.js --write
import { writeFile } from 'fs/promises'
import { fileURLToPath } from 'url'
import { fragment } from '../trigger/ble/framing.js'
import { clientProof, serverProof } from '../trigger/ble/auth.js'
import { encodeStatus, Flag } from '../trigger/ble/protocol.js'

export const FILE = fileURLToPath(new URL('../docs/test-vectors.json', import.meta.url))

export const build = () => {
  const framing = [
    { name: 'tiny', payload: 'hi', maxFragment: 20 },
    { name: 'spec example, 60 bytes at MTU 23', payload: 'A'.repeat(60), maxFragment: 20 },
    {
      name: 'request spanning several fragments',
      payload: JSON.stringify({ id: 7, op: 'config.get', d: { note: 'x'.repeat(150) } }),
      maxFragment: 100,
    },
    { name: 'exactly one fragment', payload: 'B'.repeat(17), maxFragment: 20 },
    { name: 'one byte over one fragment', payload: 'C'.repeat(18), maxFragment: 20 },
  ].map((c) => ({
    ...c,
    fragments: fragment(Buffer.from(c.payload), c.maxFragment).map((f) => f.toString('hex')),
  }))

  const secret = Buffer.from('00112233445566778899aabbccddeeff', 'hex')
  const nonce = Buffer.from(Array.from({ length: 16 }, (_, i) => i))
  const clientNonce = Buffer.from(Array.from({ length: 16 }, (_, i) => 16 + i))
  const auth = {
    secretHex: secret.toString('hex'),
    nonceB64: nonce.toString('base64'),
    clientNonceB64: clientNonce.toString('base64'),
    clientProofB64: clientProof(secret, nonce, clientNonce).toString('base64'),
    serverProofB64: serverProof(secret, nonce, clientNonce).toString('base64'),
  }

  const status = [
    {
      hex: encodeStatus({
        flags: Flag.CAMERA_READY | Flag.CLOCK_SET, phase: 'idle', configRev: 1,
        nextEventAt: 1793554715, nextEventType: 'wake', attemptsRemaining: 1,
      }).toString('hex'),
      expected: { flags: 10, phase: 'idle', configRev: 1, nextEventAt: 1793554715, nextEventType: 'wake', attemptsRemaining: 1 },
    },
    {
      hex: encodeStatus({
        flags: Flag.RECORDING | Flag.CAMERA_READY | Flag.CLOCK_SET | Flag.PAIRING_OPEN, phase: 'recording',
        configRev: 305419896, nextEventAt: 0, nextEventType: 'none', attemptsRemaining: 255,
      }).toString('hex'),
      expected: { flags: 15, phase: 'recording', configRev: 305419896, nextEventAt: 0, nextEventType: 'none', attemptsRemaining: 255 },
    },
  ]

  return { _comment: 'Generated by test/vectors.js; do not edit by hand.', framing, auth, status }
}

if (process.argv.includes('--write')) {
  await writeFile(FILE, JSON.stringify(build(), null, 2) + '\n')
  console.log('wrote', FILE)
}
