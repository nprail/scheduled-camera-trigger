#!/usr/bin/env python3
"""Signing for Kairos firmware updates (docs/ble-protocol.md, fw.*; docs/ota-plan.md).

Images are signed with ECDSA P-256 over the SHA-256 of the file. A signature is 64 bytes: r then s, each
32 bytes big-endian. The device holds the matching public keys (src/platform/signing_keys.h) and checks the
signature before it accepts any data.

  signing.py keygen KEY.pem                     make a new private key (refuses to overwrite)
  signing.py header OUT.h KEY_OR_PUB.pem...     write the public keys into the firmware header
  signing.py sign FILE...                       write FILE.sig next to each file
  signing.py verify FILE SIG                    check a signature with the public key
  signing.py manifest DIR VERSION               write DIR/manifest.json for the signed images in DIR

The private key is read from --key FILE or from the environment variable named by --key-env
(default KAIROS_SIGNING_KEY, which holds the PEM text, for CI). The release key is a GitHub Actions secret.
"""
import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, encode_dss_signature
from cryptography.exceptions import InvalidSignature

PROTOCOL = 2
CHIPS = ("esp32s3", "esp32c3")


def load_private(args):
    pem = None
    if args.key:
        pem = Path(args.key).read_bytes()
    elif os.environ.get(args.key_env):
        pem = os.environ[args.key_env].encode()
    if pem is None:
        sys.exit(f"no private key: pass --key FILE or set {args.key_env}")
    key = serialization.load_pem_private_key(pem, password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or key.curve.name != "secp256r1":
        sys.exit("the key must be an ECDSA P-256 key")
    return key


def load_public(path):
    data = Path(path).read_bytes()
    try:
        key = serialization.load_pem_private_key(data, password=None).public_key()
    except ValueError:
        key = serialization.load_pem_public_key(data)
    if not isinstance(key, ec.EllipticCurvePublicKey) or key.curve.name != "secp256r1":
        sys.exit(f"{path}: not an ECDSA P-256 key")
    return key


def point(public):
    return public.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)


def sign_file(key, path):
    der = key.sign(Path(path).read_bytes(), ec.ECDSA(hashes.SHA256()))
    r, s = decode_dss_signature(der)
    return r.to_bytes(32, "big") + s.to_bytes(32, "big")


def verify_file(public, path, sig):
    if len(sig) != 64:
        raise InvalidSignature()
    r = int.from_bytes(sig[:32], "big")
    s = int.from_bytes(sig[32:], "big")
    public.verify(encode_dss_signature(r, s), Path(path).read_bytes(), ec.ECDSA(hashes.SHA256()))


def read_sig(path):
    raw = Path(path).read_bytes()
    text = raw.strip()
    if len(raw) != 64 and re.fullmatch(rb"[0-9a-fA-F]{128}", text):
        return bytes.fromhex(text.decode())
    return raw


def cmd_keygen(args):
    out = Path(args.out)
    if out.exists():
        sys.exit(f"{out} exists; not overwriting")
    key = ec.generate_private_key(ec.SECP256R1())
    out.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    print(f"wrote {out} (keep it secret and back it up). Public key: {point(key.public_key()).hex()}")


def cmd_header(args):
    lines = [
        "// Generated by tools/signing.py header. The public keys that firmware updates must be signed with.",
        "// The first key is the current one; later keys let a release rotate to a new key. Public data: commit it.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace kairos {",
        f"constexpr unsigned kSigningKeyCount = {len(args.keys)};",
        "constexpr uint8_t kSigningKeys[][65] = {",
    ]
    for path in args.keys:
        p = point(load_public(path))
        lines.append("    {" + ", ".join(f"0x{b:02x}" for b in p) + "},")
    lines += ["};", "}  // namespace kairos", ""]
    Path(args.out).write_text("\n".join(lines))
    print(f"wrote {args.out} with {len(args.keys)} key(s)")


def cmd_sign(args):
    key = load_private(args)
    if args.header:
        wanted = ", ".join(f"0x{b:02x}" for b in point(key.public_key()))
        if wanted not in Path(args.header).read_text():
            sys.exit(f"the signing key is not one of the keys in {args.header}: devices would refuse the update")
    for f in args.files:
        sig = sign_file(key, f)
        verify_file(key.public_key(), f, sig)  # never publish a signature that does not verify
        Path(f + ".sig").write_bytes(sig)
        print(f"signed {f}")


def cmd_verify(args):
    public = load_public(args.pub)
    try:
        verify_file(public, args.file, read_sig(args.sig))
    except InvalidSignature:
        sys.exit("INVALID signature")
    print("signature ok")


def cmd_manifest(args):
    d = Path(args.dir)
    version = args.version.lstrip("v")
    public = load_public(args.pub) if args.pub else load_private(args).public_key()
    images = {}
    for chip in CHIPS:
        f = d / f"kairos-{chip}-{version}-app.bin"
        if not f.exists():
            continue
        sig = read_sig(str(f) + ".sig")
        verify_file(public, f, sig)
        images[chip] = {
            "file": f.name,
            "size": f.stat().st_size,
            "sha256": hashlib.sha256(f.read_bytes()).hexdigest(),
            "sig": sig.hex(),
        }
    if not images:
        sys.exit(f"no signed kairos-<chip>-{version}-app.bin in {d}")
    manifest = {"version": version, "protocol": PROTOCOL}
    if args.min_from:
        manifest["minFrom"] = args.min_from
    if args.notes:
        manifest["notes"] = args.notes
    manifest["images"] = images
    (d / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {d / 'manifest.json'}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--key", help="private key PEM file")
    ap.add_argument("--key-env", default="KAIROS_SIGNING_KEY", help="environment variable holding the private key PEM")
    ap.add_argument("--header", help="for sign: refuse to sign unless the key's public half is in this signing_keys.h")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("keygen"); p.add_argument("out"); p.set_defaults(fn=cmd_keygen)
    p = sub.add_parser("header"); p.add_argument("out"); p.add_argument("keys", nargs="+"); p.set_defaults(fn=cmd_header)
    p = sub.add_parser("sign"); p.add_argument("files", nargs="+"); p.set_defaults(fn=cmd_sign)
    p = sub.add_parser("verify"); p.add_argument("--pub", required=True); p.add_argument("file"); p.add_argument("sig"); p.set_defaults(fn=cmd_verify)
    p = sub.add_parser("manifest"); p.add_argument("dir"); p.add_argument("version")
    p.add_argument("--pub", help="public key to check the signatures with (default: the signing key's)")
    p.add_argument("--min-from", help="the oldest firmware that may update directly to this release")
    p.add_argument("--notes", help="a short note, or a URL to the release page")
    p.set_defaults(fn=cmd_manifest)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
